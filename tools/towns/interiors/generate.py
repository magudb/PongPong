#!/usr/bin/env python3
"""The room generator: writes the 24 room specs (data/interiors/<core|ext>/int_<id>.json) from the layout grammars of grammar.py. Package T-towns-core.

Seed-free and deterministic: the same tables give the same bytes. The 14 core specs are T-interiors-core's data, the 10 extended ones T-ext-content's; the three
fixture rooms of this package (tests/fixtures/towns/interiors) are generator output as well.

    python3 -I generate.py --list                          one line per room (size, items, posts, stand-ins)
    python3 -I generate.py --out DIR [--wave core|ext|all] [--only froebutikken,bageriet]
    python3 -I generate.py --check DIR [DIR ...]           regenerate every int_<id>.json found and fail on any difference that is not marked "hand_edited": true
    python3 -I generate.py --buildings                     the room-relevant fields of the 24 buildings as JSON (the section compares them with the Lua registry)
    python3 -I generate.py --maps DIR [--wave core|ext]    the seven line stub maps data/maps/int_<id>.map (the section compares them with InteriorRoom.stub_map)
A spec carrying `"hand_edited": true` is a deliberate edit by a person: the check skips it (and says so); everything else must equal the regenerated bytes.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.dont_write_bytecode = True                        # the tools never leave a __pycache__ in the repository, however they are started
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import grammar as G  # noqa: E402
import jsonfmt  # noqa: E402
import model as M  # noqa: E402


def generate(only: list[str] | None = None, wave: str = "all") -> dict[str, dict]:
    """id (without int_) -> spec dict, in the order of the building table."""
    out: dict[str, dict] = {}
    rooms = G.build_all()
    for bid in M.ROOMS:
        if only and bid not in only:
            continue
        if wave != "all" and M.ROOMS[bid]["wave"] != wave:
            continue
        r = rooms[bid]
        out[bid] = r.spec()
    return out


def spec_text(spec: dict) -> str:
    return jsonfmt.text(spec)


# the zone id of the OUTER area (its map's @zone): a room declares it, else entering the room would toast ZONE_<ROOM> (the zone of Hyggebyen is `city`)
ZONES = {"hyggebyen": "city", "traetoppen": "traetoppen"}


def stub_map_text(spec: dict) -> str:
    """The seven line stub map of a room (what InteriorRoom.stub_map writes): the area registry reads it, the builder script does the rest."""
    return (f"@id {spec['id']}\n@title BLD_{spec['building'].upper()}\n@projection iso\n@ambient home\n@zone {ZONES[spec['exit']['area']]}\n"
            f"@builder res://scripts/towns/interior_room.gd\n@room {spec['id']}\n")


def stand_ins_of(spec: dict) -> list[str]:
    table = json.loads((G.ROOT / "data" / "interiors" / "stand_ins.json").read_text(encoding="utf-8"))["stand_ins"]
    return sorted({it["id"] for it in spec["items"] if it["id"] in table})


def cmd_check(dirs: list[str]) -> int:
    fresh = {f"int_{bid}": s for bid, s in generate().items()}
    bad = 0
    seen = 0
    for d in dirs:
        for p in sorted(Path(d).rglob("int_*.json")):
            if "dress" in p.parts:
                continue
            seen += 1
            have = p.read_text(encoding="utf-8")
            spec = json.loads(have)
            if spec.get("hand_edited") is True:
                print(f"SKIP {p.name} (marked hand_edited)")
                continue
            want = fresh.get(spec.get("id", p.stem))
            if want is None:
                print(f"FAIL {p.name} no generator grammar produces id {spec.get('id')}")
                bad += 1
                continue
            same = spec_text(want) == have
            print(("PASS " if same else "FAIL ") + p.name + ("" if same else " differs from the regenerated spec (regenerate it, or mark a deliberate edit with hand_edited: true)"))
            bad += 0 if same else 1
    if seen == 0:
        print("PASS no_specs_found (nothing to regenerate in the given directories)")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    ap.add_argument("--only", default="")
    ap.add_argument("--wave", default="all", choices=["all", "core", "ext"])
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--check", nargs="+")
    ap.add_argument("--buildings", action="store_true")
    ap.add_argument("--maps")
    a = ap.parse_args()
    if a.buildings:
        print(json.dumps(M.ROOMS, indent=1, sort_keys=True, ensure_ascii=False))
        return 0
    if a.check:
        return cmd_check(a.check)
    only = [s for s in a.only.split(",") if s]
    specs = generate(only, a.wave)
    if a.maps:
        out = Path(a.maps)
        out.mkdir(parents=True, exist_ok=True)
        for bid, spec in specs.items():
            (out / f"int_{bid}.map").write_text(stub_map_text(spec), encoding="utf-8")
        print(f"wrote {len(specs)} stub maps to {out}")
        return 0
    if a.out:
        out = Path(a.out)
        out.mkdir(parents=True, exist_ok=True)
        for bid, s in specs.items():
            (out / f"int_{bid}.json").write_text(spec_text(s), encoding="utf-8")
        print(f"wrote {len(specs)} specs to {out}")
        return 0
    for bid, s in specs.items():
        print(f"{bid:20s} {s['cols']}x{s['rows']} items {len(s['items']):2d} posts {len(s['posts']):2d} markers {len(s['markers'])} stand-ins {stand_ins_of(s)} notes {s['notes']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
