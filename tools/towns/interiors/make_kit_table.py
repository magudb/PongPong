#!/usr/bin/env python3
"""Writes data/interiors/kit_footprints.json: the footprint and layer of the 104 kit ids, so rooms validate before the art exists and the table can be compared with the real manifest
the day it exists (towns_interiors.kit_table_matches_manifest). Package T-towns-core, amendment R-I1 (integration track).

Source: design3/integration_shop_kit.json (a lift file outside the repo: pass it with --source). The integration track already re-split it: I3 = the counter band (3) + the sign
bracket (1) + the 16 pieces the 14 core rooms draw as stand-ins + the 15 emblem plates = 35 entries; I4 = the 69 dressing pieces of the specialist sets; I5 (24 festival pieces) is
not a room kit and is left out. Ids are unchanged, only the package column moved.

    python3 -I make_kit_table.py --source /path/to/integration_shop_kit.json [--out data/interiors/kit_footprints.json] [--check]
--check compares the file that exists with what the source would produce (exit 1 on a difference); without --source the structure of the existing file is checked.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.dont_write_bytecode = True                        # the tools never leave a __pycache__ in the repository, however they are started
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jsonfmt  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUT = ROOT / "data" / "interiors" / "kit_footprints.json"
EXPECTED = {"pieces": 89, "emblems": 15, "I3": 35, "I4": 69}


def build(source: dict) -> dict:
    pieces: dict[str, dict] = {}
    for package in ("I3", "I4"):
        for set_id, entries in source["packages"][package].items():
            if set_id.startswith("_"):
                continue
            for e in entries:
                if e["id"] in pieces:
                    raise SystemExit(f"duplicate kit id {e['id']}")
                pieces[e["id"]] = {"footprint": [int(e["footprint"][0]), int(e["footprint"][1])], "layer": e["layer"], "rot_baked": int(e["rot_baked"]),
                                   "template": e["template"], "package": package, "set": set_id}
    emblems = {eid: {"package": "I3", "size": [96, 96]} for eid in source["emblems"]}
    return {
        "_doc": "Footprint and layer of the kit ids of the integration track (design3/integration_shop_kit.json, re-split: I3 = counter band + sign bracket + the 16 room pieces + 15 emblems = 35 "
                "entries, I4 = 69 dressing pieces). `pieces` are placed by the room JSON, `emblems` are the 15 plates of the door signs. Generated by tools/towns/interiors/make_kit_table.py; "
                "compared with assets/iso_props/shops/{core,special}/shops.json the day they exist.",
        "pieces": dict(sorted(pieces.items())),
        "emblems": dict(sorted(emblems.items())),
    }


def counts(table: dict) -> dict:
    pk = table["pieces"]
    return {"pieces": len(pk), "emblems": len(table["emblems"]), "I3": sum(1 for v in pk.values() if v["package"] == "I3") + len(table["emblems"]),
            "I4": sum(1 for v in pk.values() if v["package"] == "I4")}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = Path(a.out)
    if a.source:
        table = build(json.loads(Path(a.source).read_text(encoding="utf-8")))
        text = jsonfmt.text(table)
        if a.check:
            same = out.exists() and out.read_text(encoding="utf-8") == text
            print("PASS kit_table_matches_source" if same else "FAIL kit_table_matches_source")
            return 0 if same else 1
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out}: {counts(table)}")
        return 0
    table = json.loads(out.read_text(encoding="utf-8"))
    c = counts(table)
    ok = c == EXPECTED
    print(("PASS" if ok else "FAIL"), "kit_table_counts", c)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
