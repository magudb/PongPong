#!/usr/bin/env python3
"""spec_reader: the furniture catalogue of A1 = tools/art/features/home/specs/furniture_art_spec.json (replaces the spike's furniture_catalog.build_catalog()).

The spec is a copy of the REVIEWED content pack's data/furniture_art_spec.json: 130 items with English ids, one entry each

    {"id": "bed_pine", "template": "bed", "kw": {"size": "double"}, "style": {"tier": 0, "wood": "pine", "fabric": "natur"},
     "tier": 0, "rarity": "normal", "footprint": [2, 3], "layer": "floor"}

`kw` goes to the template function, `style` to furniture_traetoppen.Style, `footprint` ([w, d] tiles at rotation 0) and `layer`
(floor | rug | wall | tabletop | ceiling) are the CONTENT numbers the built piece must reproduce (check() proves it).  Names, prices, recipes and drop
sources are NOT here: they live in lua/items/furniture.lua (F1).

  python spec_reader.py [--spec FILE] [--check]       print the catalogue summary; --check builds every template and compares footprint + layer

symmetry(item) is the class the bake uses: the template's declared class, replaced for c4/c2 pieces by the MEASURED one of specs/symmetry_measured.json (measure_symmetry.py).
"""
from __future__ import annotations
import argparse, json, re
from pathlib import Path
import homepaths

DEFAULT_SPEC = homepaths.SPECS / 'furniture_art_spec.json'
RARITY = ['normal', 'uncommon', 'rare', 'unique', 'legendary']
ID_RX = re.compile(r'^[a-z][a-z0-9_]*$')
LAYERS = ('floor', 'rug', 'wall', 'tabletop', 'ceiling')


def load(path=None) -> list:
    """The items of the spec, in file order.  Raises ValueError on a malformed spec (duplicate/invalid ids, unknown rarity or layer)."""
    p = Path(path) if path else DEFAULT_SPEC
    doc = json.loads(p.read_text(encoding='utf-8'))
    items = doc['items']
    seen = set()
    for it in items:
        i = it['id']
        if not ID_RX.match(i):
            raise ValueError(f'invalid furniture id {i!r}')
        if i in seen:
            raise ValueError(f'duplicate furniture id {i!r}')
        seen.add(i)
        if it['rarity'] not in RARITY:
            raise ValueError(f'{i}: unknown rarity {it["rarity"]!r}')
        if it['layer'] not in LAYERS:
            raise ValueError(f'{i}: unknown layer {it["layer"]!r}')
        if RARITY[it['tier']] != it['rarity']:
            raise ValueError(f'{i}: tier {it["tier"]} is not rarity {it["rarity"]}')
        for k in ('template', 'kw', 'style', 'footprint'):
            if k not in it:
                raise ValueError(f'{i}: missing {k}')
    return items


def by_id(items) -> dict:
    return {i['id']: i for i in items}


def build(item):
    """FSpec of one item (model + footprint + layer + symmetry ...): TEMPLATES[template](Style(**style), **kw)."""
    import furniture_traetoppen as ft
    return ft.TEMPLATES[item['template']](ft.Style(**item['style']), **item['kw'])


SYMMETRY_FILE = homepaths.SPECS / 'symmetry_measured.json'
_MEASURED = {}


def measured_symmetry() -> dict:
    """{id: measured class} of specs/symmetry_measured.json (generated by measure_symmetry.py; empty when the file does not exist yet)."""
    if 'v' not in _MEASURED:
        _MEASURED['v'] = {i: e['class'] for i, e in json.loads(SYMMETRY_FILE.read_text(encoding='utf-8'))['items'].items()} if SYMMETRY_FILE.exists() else {}
    return _MEASURED['v']


def declared_symmetry(item, spec=None) -> str:
    """the class the TEMPLATE declares (c4 | c2 | wall2 | none); what measure_symmetry.py checks - never what the bake uses on its own."""
    spec = spec or build(item)
    return 'wall2' if spec.layer == 'wall' else spec.sym


def symmetry(item, spec=None) -> str:
    """c4 | c2 | wall2 | none - the symmetry class that decides how many rotations are baked (wall pieces: two).
    A template that declares c4 or c2 is MEASURED (measure_symmetry.py, specs/symmetry_measured.json): the measured class replaces the declared one."""
    declared = declared_symmetry(item, spec)
    if declared in ('c4', 'c2'):
        return measured_symmetry().get(item['id'], declared)
    return declared


def rotations_needed(sym: str) -> list:
    """Rotations k (yaw k*90) that must exist as FILES for a piece of this symmetry class (true bakes): c4 -> [0], c2/wall2 -> [0, 1], none -> [0, 1, 2, 3]."""
    return {'c4': [0], 'c2': [0, 1], 'wall2': [0, 1]}.get(sym, [0, 1, 2, 3])


def check(items) -> list:
    """Build every template and compare with the content numbers; returns a list of problems (empty = the art matches the spec)."""
    problems = []
    for it in items:
        try:
            s = build(it)
        except Exception as e:                                   # a template that raises is a spec problem, report it with the id
            problems.append(f'{it["id"]}: template {it["template"]} failed: {e!r}')
            continue
        if list(s.fp) != list(it['footprint']):
            problems.append(f'{it["id"]}: footprint {list(s.fp)} != spec {list(it["footprint"])}')
        if s.layer != it['layer']:
            problems.append(f'{it["id"]}: layer {s.layer} != spec {it["layer"]}')
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--spec', default=str(DEFAULT_SPEC)); ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    items = load(a.spec)
    cells = {}
    for it in items:
        cells.setdefault(it['template'], {}).setdefault(it['rarity'], 0)
        cells[it['template']][it['rarity']] += 1
    print(f'{len(items)} items, {len(cells)} templates, {sum(len(v) for v in cells.values())} (template, rarity) cells')
    if a.check:
        probs = check(items)
        for p in probs:
            print('PROBLEM', p)
        print('check:', 'OK, every template builds and matches footprint + layer' if not probs else f'{len(probs)} problem(s)')
        raise SystemExit(1 if probs else 0)


if __name__ == '__main__':
    main()
