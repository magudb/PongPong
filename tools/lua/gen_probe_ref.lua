-- tools/lua/gen_probe_ref.lua
-- Generates tests/fixtures/lua/probe_expected.json: every case of tools/lua/probe_cases.lua is run through REAL Lua 5.4
-- (the reference semantics) against the probe files in tests/fixtures/lua, and the result + side effects are recorded.
-- tests/sections/data.gd replays the same cases through the project's LuaRuntime and compares (data.lua_probes).
--
--   tools/lua/gen_probe_ref.sh            (needs `lua5.4` or `lua` on the PATH; run from anywhere, writes the fixture)
--
-- The stub `api` records effects instead of changing a game. Like the game, a BARE identifier that is not defined reads
-- the world flag of that name (the env falls back to the case's flags), so the content pattern `context.x or x or 1` has
-- the same meaning here and in LuaRuntime.

local FIXTURES = arg[1] or "tests/fixtures/lua"
local CASES = arg[2] or "tools/lua/probe_cases.lua"
local SER = arg[3] or "tools/lua/ref_ser.lua"

dofile(SER)
local cases = dofile(CASES)
local out = {}

for _, c in ipairs(cases) do
  local eff = { flags = {}, gold = 0, notifs = {}, emits = {} }
  local function flag(k) return c.flags[k] end
  local api = {
    has_flag = function(k) return not not flag(k) end,
    get_flag = function(k) return flag(k) end,
    has_item = function() return false end,
    get_gold = function() return 0 end,
    set_flag = function(k, v) if v == nil then v = true end eff.flags[k] = v end,
    add_gold = function(n) eff.gold = eff.gold + n end,
    notification = function(t, m) eff.notifs[#eff.notifs + 1] = { t, m } end,
    emit = function(e, p) eff.emits[#eff.emits + 1] = { e, p or {} } end,
    log = function() end,
  }
  local env = setmetatable({ api = api }, { __index = function(_, k)
    local v = flag(k)
    if v ~= nil then return v end
    return _G[k]
  end })
  local rec = { probe = c.probe, label = c.label, fn = c.fn, args = c.args, flags = c.flags, mode = c.mode, lint = c.lint }
  local ok, err = pcall(function()
    local f = assert(loadfile(FIXTURES .. "/" .. c.probe .. ".lua", "t", env))
    env.__ret = f()
  end)
  local ref = {}
  if not ok then
    ref.error = tostring(err)
  else
    local fn = rawget(env, c.fn)
    if not fn and type(env.__ret) == "table" then fn = env.__ret[c.fn] end
    if not fn then
      ref.nofn = true
    else
      local ok2, res = pcall(fn, table.unpack(c.args))
      if ok2 then ref.result = res else ref.error = tostring(res) end
    end
  end
  ref.effects = eff
  rec.ref = ref
  out[#out + 1] = ser(rec)
end

io.write('{"generator":"' .. _VERSION .. '","note":"generated by tools/lua/gen_probe_ref.lua with real Lua; do not edit",\n"cases":[\n')
io.write(table.concat(out, ",\n"))
io.write("\n]}\n")
